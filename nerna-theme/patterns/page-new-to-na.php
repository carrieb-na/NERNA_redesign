<!-- /wp:heading -->
<!-- wp:list {"ordered":true,"className":"nerna-steps"} -->
<ol class="wp-block-list nerna-steps"><!-- wp:list-item -->
<li><strong>Pick a meeting.</strong> Use the <a href="/meetings/">meeting finder</a> or call the helpline. &#8220;Open&#8221; meetings welcome anyone. &#8220;Closed&#8221; meetings are for people who think they may have a drug problem.</li>
<!-- /wp:list-item -->
